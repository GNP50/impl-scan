//! Renderer helpers, strict mode and the built-in partials.

use impl_scan::{Cfg, Registry, Renderer, Scanner};

fn registry() -> Registry {
    static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!("impl-scan-render-{}-{n}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(
        dir.join("lib.rs"),
        r#"
        pub trait S {}
        /// Picks "the" <largest> block.
        #[register(aliases = ["MFS"])]
        pub struct MaxFreeSlot; impl S for MaxFreeSlot {}
        pub struct FirstFit; impl S for FirstFit {}
        "#,
    )
    .unwrap();
    Scanner::new(&dir)
        .trait_impls("S")
        .group("s")
        .cfg(Cfg::new())
        .emit_cargo(false)
        .scan()
        .unwrap()
}

fn render(template: &str) -> String {
    Renderer::new()
        .emit_cargo(false)
        .render_str(template, &registry())
        .unwrap()
}

#[test]
fn helpers() {
    assert_eq!(
        render("{{#each s}}{{snake type}} {{pascal name}} {{camel name}} {{screaming type}} {{lower name}}|{{/each}}"),
        "first_fit FirstFit firstFit FIRST_FIT first_fit|max_free_slot MaxFreeSlot maxFreeSlot MAX_FREE_SLOT max_free_slot|"
    );
    assert_eq!(
        render("{{#each s}}{{join aliases \",\"}};{{/each}}"),
        ";MFS;"
    );
    // No HTML escaping, and quote produces a valid Rust literal.
    assert_eq!(
        render("{{#each s}}{{#if doc}}{{quote doc}}{{/if}}{{/each}}"),
        r#""Picks \"the\" <largest> block.""#
    );
    let multi = Renderer::new().emit_cargo(false).data("d", "a\n\nb");
    assert_eq!(
        multi.render_str("{{doc d indent=2}}", &registry()).unwrap(),
        "/// a\n  ///\n  /// b"
    );
    assert_eq!(render("{{doc \"\" fallback=\"x\"}}"), "/// x");
}

#[test]
fn strict_mode_rejects_misspelled_fields() {
    let err = Renderer::new()
        .emit_cargo(false)
        .render_str("{{#each s}}{{nmae}}{{/each}}", &registry())
        .unwrap_err();
    assert!(err.to_string().contains("nmae"), "{err}");
    // Optional partial parameters tested with #if are fine.
    assert!(render("{{> registry_enum enum=\"K\" items=s}}").contains("pub enum K"));
}

#[test]
fn registry_enum_partial() {
    let out = render("{{> registry_enum enum=\"Kind\" items=s derive=\"serde::Serialize\"}}");
    assert!(out.contains("Ord, serde::Serialize)]"), "{out}");
    assert!(
        out.contains("    /// Picks \"the\" <largest> block.\n    MaxFreeSlot,"),
        "{out}"
    );
    assert!(out.contains("    /// FirstFit\n    FirstFit,"), "{out}");
    assert!(
        out.contains("&[Kind::FirstFit, Kind::MaxFreeSlot, ]"),
        "{out}"
    );
    assert!(
        out.contains(
            r#""MAX_FREE_SLOT" | "MFS" => ::core::option::Option::Some(Kind::MaxFreeSlot)"#
        ),
        "{out}"
    );
}

#[test]
fn dispatch_block_sees_each_item() {
    let out = render(
        "{{#*inline \"arm\"}}run::<T>({{quote name}}){{/inline}}{{> dispatch on=\"k\" enum=\"Kind\" items=s body=\"arm\"}}",
    );
    assert!(out.contains("Kind::FirstFit => {"), "{out}");
    assert!(out.contains("type T = crate::FirstFit;"), "{out}");
    assert!(out.contains(r#"run::<T>("MAX_FREE_SLOT")"#), "{out}");
}

#[test]
fn render_to_file_writes_only_on_change() {
    let dir = std::env::temp_dir().join(format!("impl-scan-out-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    let template = dir.join("t.hbs");
    std::fs::write(&template, "{{#each s}}{{name}}\n{{/each}}").unwrap();
    let out = dir.join("gen/out.rs");
    let renderer = Renderer::new().emit_cargo(false);
    assert!(renderer
        .render_to_file(&template, &registry(), &out)
        .unwrap());
    assert!(!renderer
        .render_to_file(&template, &registry(), &out)
        .unwrap());
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(
        text.starts_with("// @generated by impl-scan from t.hbs."),
        "{text}"
    );
    assert!(text.ends_with("FIRST_FIT\nMAX_FREE_SLOT\n"), "{text}");
}
